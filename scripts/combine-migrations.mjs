import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

// Regenerates supabase/combined_migrations.sql from supabase/migrations/*.sql
// so there's a single copy-paste-able script for the Supabase SQL Editor.
// Run this after adding a new migration file — supabase/combined_migrations.sql
// is generated output, not something to hand-edit.

const rootDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const migrationsDir = join(rootDir, "supabase", "migrations");
const outputPath = join(rootDir, "supabase", "combined_migrations.sql");

const files = readdirSync(migrationsDir)
  .filter((f) => f.endsWith(".sql"))
  .sort();

const header = `-- Combined migrations ${files[0]?.slice(0, 4)}-${files.at(-1)?.slice(0, 4)}, generated by scripts/combine-migrations.mjs.
-- Each source file is idempotent, so this whole script is safe to re-run.
-- Source of truth is the individual files in supabase/migrations/ — regenerate
-- this if you add a new one, don't hand-edit it.
`;

const body = files
  .map((file) => {
    const sql = readFileSync(join(migrationsDir, file), "utf8");
    return `-- ============================================================\n-- ${file}\n-- ============================================================\n${sql}`;
  })
  .join("\n");

writeFileSync(outputPath, `${header}\n${body}`);
console.log(`Wrote ${outputPath} from ${files.length} migration(s): ${files.join(", ")}`);
